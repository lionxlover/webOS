/* Store app — PDF Fox: reader for PDF files stored in the VFS (data-URL payloads).
   Generates a real, valid sample PDF on first run. */
(function () {
  'use strict';
  const H = LX.h;

  // Minimal-but-valid PDF generator (Helvetica, multi-page text)
  function makePDF(pages) {
    const objs = [];
    const add = (s) => { objs.push(s); return objs.length - 1 + 1; }; // returns object number (1-based)
    // 1: catalog, 2: pages tree (placeholder), 3: font, then page objects
    const catN = add(''); const pagesN = add(''); const fontN = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
    const pageRefs = [];
    pages.forEach((lines) => {
      const contentN = add('');
      const pageN = add('');
      objs[pageN - 1] = pageN + ' 0 obj\n<< /Type /Page /Parent ' + pagesN + ' 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 ' + fontN + ' 0 R >> >> /Contents ' + contentN + ' 0 R >>\nendobj\n';
      let stream = 'BT /F1 11 Tf 72 720 Td 16 TL\n';
      lines.forEach((l, i) => {
        const t = String(l).replace(/[\u2014\u2192\u2022\u00b7\u2261\u203a\u2039]/g, '-').replace(/[^\x20-\xff]/g, '').replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
        stream += (i === 0 ? '28 TL 24 Tf (' + t + ') Tj 14 TL 11 Tf T*\n' : '(' + t + ') Tj T*\n');
      });
      stream += 'ET';
      objs[contentN - 1] = contentN + ' 0 obj\n<< /Length ' + stream.length + ' >>\nstream\n' + stream + '\nendstream\nendobj\n';
      pageRefs.push(pageN);
    });
    objs[catN - 1] = catN + ' 0 obj\n<< /Type /Catalog /Pages ' + pagesN + ' 0 R >>\nendobj\n';
    objs[pagesN - 1] = pagesN + ' 0 obj\n<< /Type /Pages /Kids [' + pageRefs.map((p) => p + ' 0 R').join(' ') + '] /Count ' + pageRefs.length + ' >>\nendobj\n';
    let out = '%PDF-1.4\n';
    const offsets = [];
    objs.forEach((o, i) => { offsets.push(out.length); out += o; });
    const xrefPos = out.length;
    out += 'xref\n0 ' + (objs.length + 1) + '\n0000000000 65535 f \n';
    offsets.forEach((off) => { out += String(off).padStart(10, '0') + ' 00000 n \n'; });
    out += 'trailer\n<< /Size ' + (objs.length + 1) + ' /Root ' + catN + ' 0 R >>\nstartxref\n' + xrefPos + '\n%%EOF';
    return btoa(out);
  }

  LX.apps.register({
    id: 'pdffox', name: 'PDF Fox', icon: 'book', color: '#F28B82', category: 'Utilities',
    pkg: true, pkgVersion: '1.0', pkgSize: 16, developer: 'Leonux Labs', downloads: 1020,
    desc: 'Read PDF documents', longDesc: 'Open PDF files stored in your Leonux filesystem. PDF Fox renders them with the browser’s built-in engine and can generate a sample guide so you can try it right away.',
    permissions: ['Local storage'], changelog: 'First release.',
    canOpenExt: ['pdf'],
    width: 820, height: 640, minWidth: 480, minHeight: 420,
    open(win, args) {
      const SAMPLE = '/home/user/Documents/Leonux-Guide.pdf';
      if (!LX.vfs.exists(SAMPLE)) {
        LX.vfs.write(SAMPLE, 'data:application/pdf;base64,' + makePDF([
          ['LEONUX OS 2 — QUICK GUIDE', '', 'Welcome to your new desktop. Here is how to get the most out of it:', '', '1. The App Store — install 26+ real apps and games.', '2. Spaces — Ctrl+Alt+Arrows switch virtual desktops.', '3. Mission Control — Ctrl+Alt+Up shows every window.', '4. The Dock — hover it: icons magnify like a certain fruit OS.', '5. Search — Ctrl+Space finds apps, files and solves math.', '', 'This PDF was generated by PDF Fox inside Leonux.'],
          ['PAGE TWO — OFFLINE & INSTALL', '', 'Leonux installs to your system as a PWA:', 'open the browser menu and choose Install. After that it', 'runs completely offline — every app, game and file stays', 'on your device.', '', 'Enjoy your stay on the savanna.']
        ]), { mime: 'application/pdf' });
      }

      const view = H('div', { class: 'pf-view grow' });
      const list = H('div', { class: 'pf-list' });
      const cur = H('div', { class: 'pf-cur muted' });

      function findPDFs() {
        const out = [];
        (function walk(p) { try { LX.vfs.ls(p).forEach((s) => { if (s.name[0] === '.') return; if (s.type === 'dir') walk(s.path); else if (LX.vfs.ext(s.name) === 'pdf') out.push(s); }); } catch (e) {} })(LX.vfs.HOME);
        return out;
      }
      function openPDF(p) {
        const d = LX.vfs.read(p);
        if (!d || d.indexOf('data:application/pdf') !== 0) { view.innerHTML = ''; view.appendChild(H('div', { class: 'center', style: { padding: '40px' } }, H('div', { html: LX.icon('alert', 40) }), H('div', { class: 'muted', text: 'This PDF payload is not stored as a data URL — cannot render.' }))); return; }
        view.innerHTML = '';
        const frame = H('iframe', { class: 'pf-frame', src: d, title: LX.vfs.basename(p) });
        view.appendChild(frame);
        cur.textContent = LX.vfs.basename(p) + ' · ' + LX.fmtBytes((d.length || 0) * 0.75);
        win.setTitle(LX.vfs.basename(p) + ' — PDF Fox');
      }
      function paintList() {
        list.innerHTML = '';
        const pdfs = findPDFs();
        if (!pdfs.length) { list.appendChild(H('div', { class: 'muted', style: { padding: '10px' }, text: 'No PDFs found.' })); return; }
        pdfs.slice(0, 30).forEach((s) => list.appendChild(H('div', { class: 'list-item pf-item', onclick: () => openPDF(s.path) },
          H('span', { html: LX.icon('book', 15) }), H('span', { class: 'grow ellipsis', text: s.name.replace(/\.pdf$/i, '') }))));
      }

      win.body.append(
        H('div', { class: 'toolbar' },
          H('button', { class: 'btn sm', html: LX.icon('folder', 13) + ' Open…', onclick: () => LX.dialog.openFile({ title: 'Open PDF', path: LX.vfs.HOME, exts: ['pdf'] }).then((p) => { if (p) openPDF(p); }) }),
          H('button', { class: 'btn sm ghost', html: LX.icon('refresh', 13) + ' Rescan', onclick: () => { paintList(); } }),
          H('span', { class: 'grow' }), cur),
        H('div', { class: 'pf-main' }, H('div', { class: 'sidebar pf-side' }, H('div', { class: 'pf-side-h', text: 'PDFs on this device' }), list), view));
      paintList();
      if (args && args.path) openPDF(args.path);
      else openPDF(SAMPLE);
    },
  });
})();

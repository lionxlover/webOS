#!/usr/bin/env python3
"""Generate store/starter.js from store/ (repo.json + apps/*.json + apps/*.zip).

starter.js is a classic script defining window.LX_STARTER so the bundled
'Leonux Starter Store' works from file:// (where fetch() is unavailable).
Run:  python3 scripts/build_starter.py
"""
import base64, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STORE = os.path.join(ROOT, 'store')

def main():
    repo = json.load(open(os.path.join(STORE, 'repo.json'), encoding='utf-8'))
    apps, zips = {}, {}
    adir = os.path.join(STORE, 'apps')
    for fn in sorted(os.listdir(adir)):
        p = os.path.join(adir, fn)
        stem, ext = os.path.splitext(fn)
        if ext == '.json':
            apps[stem] = json.load(open(p, encoding='utf-8'))
        elif ext == '.zip':
            zips[stem] = base64.b64encode(open(p, 'rb').read()).decode('ascii')
    out = {'repo': repo, 'apps': apps, 'zips': zips}
    js = ('/* AUTO-GENERATED by scripts/build_starter.py - do not edit. */\n'
          'window.LX_STARTER=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
    with open(os.path.join(STORE, 'starter.js'), 'w', encoding='utf-8') as f:
        f.write(js)
    print('store/starter.js: %d apps, %d zips, %.1f KB' % (len(apps), len(zips), len(js.encode()) / 1024))

if __name__ == '__main__':
    sys.exit(main())
